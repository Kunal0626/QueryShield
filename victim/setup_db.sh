#!/usr/bin/env bash
#
# One-time local database setup for the QueryShield demo.
#
# What it does:
#   1. Creates the `queryshield` database.
#   2. Creates a dedicated `qsdemo`@`localhost` user that can only SELECT from
#      that one database (least privilege: even a stacked DROP/INSERT that
#      slipped through could not change or destroy data).
#   3. Loads schema.sql and the fake seed data.
#   4. Writes victim/local.properties (gitignored) with the connection string
#      and a randomly generated password for the qsdemo user.
#
# You are prompted for your MySQL *root* password by MySQL itself. This script
# never sees it, never stores it, and never sends it anywhere. The only
# password it writes is the random one it just generated for qsdemo.
#
# Re-running is safe: it resets qsdemo's password and reloads the schema.

set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
SQL_DIR="$HERE/sql"
PROPS="$HERE/local.properties"

if ! command -v mysql >/dev/null 2>&1; then
  echo "error: 'mysql' client not found on PATH." >&2
  echo "       MySQL 9.5 is installed at /usr/local/mysql-9.5.0-macos15-arm64/bin" >&2
  echo "       Add it to PATH, e.g.: export PATH=\"/usr/local/mysql-9.5.0-macos15-arm64/bin:\$PATH\"" >&2
  exit 1
fi

DB=queryshield
APPUSER=qsdemo
DBHOST=127.0.0.1
DBPORT=3306

# Random, local-only password for the demo account. Alnum only, so it needs no
# quoting/escaping anywhere it is used.
PASS="$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 24)"

echo "QueryShield demo DB setup"
echo "  database : $DB"
echo "  app user : $APPUSER@localhost  (SELECT on $DB only)"
echo
echo "You will now be asked for your MySQL ROOT password (by MySQL, not by us)."
echo

# One combined stream => root is prompted exactly once. schema.sql/seed.sql
# contain no USE statement; we select the database first here.
{
  cat <<SQL
CREATE DATABASE IF NOT EXISTS \`$DB\`
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '$APPUSER'@'localhost' IDENTIFIED BY '$PASS';
ALTER USER '$APPUSER'@'localhost' IDENTIFIED BY '$PASS';
REVOKE ALL PRIVILEGES, GRANT OPTION FROM '$APPUSER'@'localhost';
GRANT SELECT ON \`$DB\`.* TO '$APPUSER'@'localhost';
FLUSH PRIVILEGES;
USE \`$DB\`;
SQL
  cat "$SQL_DIR/schema.sql"
  cat "$SQL_DIR/seed.sql"
} | mysql -u root -p --host="$DBHOST" --port="$DBPORT"

# Write the gitignored local credentials file with restrictive permissions.
umask 077
cat > "$PROPS" <<PROP
# LOCAL ONLY. Generated by victim/setup_db.sh. Gitignored. Do not commit.
# Regenerate any time by re-running: bash victim/setup_db.sh
db.url=jdbc:mysql://$DBHOST:$DBPORT/$DB?allowPublicKeyRetrieval=true&sslMode=DISABLED
db.user=$APPUSER
db.password=$PASS
PROP
chmod 600 "$PROPS"

echo
echo "Done."
echo "  loaded   : schema + fake seed data"
echo "  wrote    : $PROPS  (gitignored, chmod 600)"
echo
echo "Next: start the demo app with  ->  make victim"
