package com.queryshield.eval;

import com.queryshield.detect.Detector;
import com.queryshield.detect.DetectorConfig;
import com.queryshield.detect.SignatureSet;
import com.queryshield.detect.Verdict;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Offline evaluation harness: runs the detector directly on the labelled
 * dataset (no HTTP, no database) and reports how well each configuration
 * detects attacks without flagging benign input.
 *
 * <p>It evaluates on the <b>dev</b> split (used while tuning signatures/rules)
 * and the untouched <b>test</b> split (the number that counts), for each
 * configuration, and writes a Markdown report with a provenance header so every
 * number is traceable to a machine, a dataset and a commit.
 *
 * <p>Run: {@code make eval}
 */
public final class EvalHarness {

    private static final String SIGNATURES = "/signatures.txt";

    public static void main(String[] args) throws IOException {
        Path dataDir = Path.of(arg(args, "--data=", "data"));
        Path outFile = Path.of(arg(args, "--out=", "eval/results/eval.md"));

        SignatureSet signatures = SignatureSet.fromResource(SIGNATURES);
        List<Row> rows = new ArrayList<>();
        rows.addAll(Csv.readRows(dataDir.resolve("attacks.csv")));
        rows.addAll(Csv.readRows(dataDir.resolve("benign.csv")));

        // The three compared configurations: signatures only, + normalizer,
        // + tokenizer rules and scoring.
        List<DetectorConfig> configs = List.of(
                DetectorConfig.v1(), DetectorConfig.v2(), DetectorConfig.v3());

        StringBuilder md = new StringBuilder();
        header(md, signatures, rows);

        summaryTable(md, configs, signatures, rows);

        thresholdSweep(md, signatures, rows);

        for (DetectorConfig cfg : configs) {
            detail(md, cfg, signatures, rows, "test");
        }
        // Dev details too, so the tuning basis is visible.
        for (DetectorConfig cfg : configs) {
            detail(md, cfg, signatures, rows, "dev");
        }

        Files.createDirectories(outFile.getParent());
        Files.writeString(outFile, md.toString(), StandardCharsets.UTF_8);

        System.out.println(md);
        System.out.println("wrote " + outFile);
    }

    // ----------------------------------------------------------------- report

    private static void header(StringBuilder md, SignatureSet sigs, List<Row> rows) {
        long attacks = rows.stream().filter(Row::isAttack).count();
        long benign = rows.size() - attacks;
        md.append("# QueryShield evaluation\n\n");
        md.append("_Generated by `make eval`. Re-run to reproduce._\n\n");
        md.append("| | |\n|---|---|\n");
        md.append("| Date | ").append(ZonedDateTime.now().format(DateTimeFormatter.ISO_OFFSET_DATE_TIME)).append(" |\n");
        md.append("| Machine | ").append(System.getProperty("os.name")).append(' ')
                .append(System.getProperty("os.version")).append(' ')
                .append(System.getProperty("os.arch")).append(" |\n");
        md.append("| Java | ").append(System.getProperty("java.version")).append(" |\n");
        md.append("| Git commit | ").append(gitCommit()).append(" |\n");
        md.append("| Signatures | ").append(sigs.size()).append(" |\n");
        md.append("| Dataset | ").append(rows.size()).append(" rows (")
                .append(attacks).append(" attack, ").append(benign).append(" benign) |\n\n");
        md.append("Positive class = attack. Recall = attacks blocked / attacks. ")
                .append("FPR = benign blocked / benign. Precision = attacks blocked / all blocked.\n\n");
    }

    private static void summaryTable(StringBuilder md, List<DetectorConfig> configs,
                                     SignatureSet sigs, List<Row> rows) {
        md.append("## Summary\n\n");
        md.append("| config | split | recall | FPR | precision | F1 | accuracy | TP | FP | TN | FN |\n");
        md.append("|--------|-------|-------:|----:|----------:|---:|---------:|---:|---:|---:|---:|\n");
        for (DetectorConfig cfg : configs) {
            for (String split : List.of("dev", "test")) {
                Eval e = evaluate(cfg, sigs, rows, split);
                Metrics m = e.metrics;
                md.append("| ").append(cfg.name()).append(" | ").append(split)
                        .append(" | ").append(pct(m.recall()))
                        .append(" | ").append(pct(m.falsePositiveRate()))
                        .append(" | ").append(pct(m.precision()))
                        .append(" | ").append(pct(m.f1()))
                        .append(" | ").append(pct(m.accuracy()))
                        .append(" | ").append(m.tp()).append(" | ").append(m.fp())
                        .append(" | ").append(m.tn()).append(" | ").append(m.fn())
                        .append(" |\n");
            }
        }
        md.append('\n');
    }

    /** Sweep the v3 score threshold on the DEV split, so the chosen value is
     *  shown to be a tuning decision made on dev, not test. */
    private static void thresholdSweep(StringBuilder md, SignatureSet sigs, List<Row> rows) {
        md.append("## v3 score-threshold tuning (dev split only)\n\n");
        md.append("The threshold is picked here, on dev, then frozen for the test numbers above. ")
                .append("`DetectorConfig.V3_THRESHOLD = ").append(DetectorConfig.V3_THRESHOLD)
                .append("`.\n\n");
        md.append("| threshold | recall | FPR | precision | F1 |\n");
        md.append("|----------:|-------:|----:|----------:|---:|\n");
        for (int t = 1; t <= 8; t++) {
            Metrics m = evaluate(DetectorConfig.v3(t), sigs, rows, "dev").metrics;
            md.append("| ").append(t)
                    .append(" | ").append(pct(m.recall()))
                    .append(" | ").append(pct(m.falsePositiveRate()))
                    .append(" | ").append(pct(m.precision()))
                    .append(" | ").append(pct(m.f1()))
                    .append(" |\n");
        }
        md.append('\n');
    }

    private static void detail(StringBuilder md, DetectorConfig cfg, SignatureSet sigs,
                               List<Row> rows, String split) {
        Eval e = evaluate(cfg, sigs, rows, split);
        md.append("## ").append(cfg.name()).append(" -- ").append(split).append(" details\n\n");

        // Misses (false negatives) grouped by attack category.
        Map<String, List<Row>> missByCat = new TreeMap<>();
        for (Row r : e.falseNegatives) {
            missByCat.computeIfAbsent(r.category(), k -> new ArrayList<>()).add(r);
        }
        md.append("**Missed attacks (FN): ").append(e.falseNegatives.size()).append("**\n\n");
        if (missByCat.isEmpty()) {
            md.append("_none_\n\n");
        } else {
            for (var entry : missByCat.entrySet()) {
                md.append("- _").append(entry.getKey()).append("_: ");
                List<String> items = new ArrayList<>();
                for (Row r : entry.getValue()) {
                    items.add(r.id() + " `" + r.input() + "`");
                }
                md.append(String.join("; ", items)).append('\n');
            }
            md.append('\n');
        }

        // False positives (benign blocked), listed exactly.
        md.append("**False positives (FP): ").append(e.falsePositives.size()).append("**\n\n");
        if (e.falsePositives.isEmpty()) {
            md.append("_none_\n\n");
        } else {
            for (Row r : e.falsePositives) {
                md.append("- ").append(r.id()).append(" _(").append(r.category()).append(")_ `")
                        .append(r.input()).append("`\n");
            }
            md.append('\n');
        }
    }

    // --------------------------------------------------------------- evaluate

    private record Eval(Metrics metrics, List<Row> falseNegatives, List<Row> falsePositives) {
    }

    private static Eval evaluate(DetectorConfig cfg, SignatureSet sigs, List<Row> rows, String split) {
        Detector detector = new Detector(cfg, sigs);
        Metrics metrics = new Metrics();
        List<Row> fn = new ArrayList<>();
        List<Row> fp = new ArrayList<>();
        for (Row r : rows) {
            if (!r.split().equals(split)) {
                continue;
            }
            Verdict v = detector.inspect("input", r.input());
            metrics.record(r.isAttack(), v.block());
            if (r.isAttack() && !v.block()) {
                fn.add(r);
            } else if (!r.isAttack() && v.block()) {
                fp.add(r);
            }
        }
        return new Eval(metrics, fn, fp);
    }

    // ---------------------------------------------------------------- helpers

    private static String pct(double v) {
        return String.format("%.1f%%", v * 100);
    }

    private static String gitCommit() {
        try {
            Process p = new ProcessBuilder("git", "rev-parse", "--short", "HEAD")
                    .redirectErrorStream(true).start();
            String out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8).strip();
            return p.waitFor() == 0 && !out.isEmpty() ? out : "unknown";
        } catch (IOException | InterruptedException e) {
            Thread.currentThread().interrupt();
            return "unknown";
        }
    }

    private static String arg(String[] args, String prefix, String def) {
        for (String a : args) {
            if (a.startsWith(prefix)) {
                return a.substring(prefix.length());
            }
        }
        return def;
    }

    private EvalHarness() {
    }
}
