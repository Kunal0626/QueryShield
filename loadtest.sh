#!/usr/bin/env bash
#
# loadtest.sh -- measure the proxy's throughput/latency overhead.
#
# Starts the victim (:8081) and the proxy in block mode (:8080), then runs the
# Java load generator against the same benign request both ways (direct vs
# through the proxy), for TWO endpoints:
#   - /search?q=mug : DB-backed (realistic end-to-end), where the MySQL query
#     dominates and the proxy's own cost is small by comparison.
#   - /            : the victim index, no DB, which isolates the proxy's own
#     per-request cost (inspection + the extra forward hop).
# Writes eval/results/phase9-loadtest.md with a provenance header.
#
# Extra args pass through to LoadGen, e.g.: bash loadtest.sh --duration=15
# Prerequisite: bash victim/setup_db.sh
set -uo pipefail
cd "$(dirname "$0")"

[ -f victim/local.properties ] || { echo "run: bash victim/setup_db.sh first"; exit 1; }
if lsof -nP -iTCP:8080 -iTCP:8081 -sTCP:LISTEN >/dev/null 2>&1; then
  echo "error: port 8080 or 8081 already in use; stop the other process first." >&2
  exit 1
fi

echo "== building ==" >&2
make -s build
CP="out/main:src/main/resources:$(ls lib/mysql-connector-j-*.jar)"

java -cp "$CP" com.queryshield.victim.VictimApp --port=8081 >/tmp/qs_load_victim.log 2>&1 & VPID=$!
java -cp "$CP" com.queryshield.proxy.ProxyServer >/tmp/qs_load_proxy.log 2>&1 & XPID=$!
cleanup(){ kill "$VPID" "$XPID" 2>/dev/null || true; }
trap cleanup EXIT

for _ in $(seq 1 40); do
  curl -fs http://127.0.0.1:8081/health >/dev/null 2>&1 \
    && curl -fs http://127.0.0.1:8080/health >/dev/null 2>&1 && break
  sleep 0.5
done

REPORT=eval/results/phase9-loadtest.md
mkdir -p eval/results
{
  echo "# QueryShield -- Phase 9 load test"
  echo
  echo "_Generated by \`make loadtest\`. Re-run to reproduce (numbers vary run to run)._"
  echo
  echo "| | |"
  echo "|---|---|"
  echo "| Date | $(date -u '+%Y-%m-%dT%H:%M:%SZ') (UTC) |"
  echo "| Machine | $(uname -msr) |"
  echo "| Java | $(java -version 2>&1 | head -1) |"
  echo "| Git commit | $(git rev-parse --short HEAD) |"
  echo
  java -cp "$CP" com.queryshield.eval.LoadGen \
    --name="DB-backed request: /search?q=mug (end-to-end)" \
    --direct="http://127.0.0.1:8081/search?q=mug" \
    --proxy="http://127.0.0.1:8080/search?q=mug" "$@" --threads=16 --duration=10 --warmup=3
  java -cp "$CP" com.queryshield.eval.LoadGen \
    --name="No-DB request: / (isolates the proxy's own cost)" \
    --direct="http://127.0.0.1:8081/" \
    --proxy="http://127.0.0.1:8080/" "$@" --threads=16 --duration=10 --warmup=3
  echo "_Caveat: victim and proxy share one machine over loopback, so there is no"
  echo "network latency to hide behind; absolute numbers are machine-specific. For"
  echo "the DB-backed request the MySQL query dominates, so the proxy's cost there is"
  echo "within run-to-run variance (the sign of the change may flip between runs)."
  echo "The no-DB row is the honest measure of the proxy's own per-request overhead._"
} | tee "$REPORT"
